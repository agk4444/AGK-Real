"""Level 4 — Codegen golden tests (AGK-Real v1 test plan).

Each test asserts the EXACT Python output. Every output is also verified
with ast.parse (generated code must always be syntactically valid Python).
"""

import ast as py_ast

import pytest

from agk.parser import parse
from agk.semantic import analyze
from agk.codegen import generate


def gen(src):
    """Full pipeline: parse -> analyze -> generate. Validates the output
    parses as Python, then returns it."""
    prog = parse(src, filename="test.agk")
    prog, _warnings = analyze(prog, filename="test.agk")
    out = generate(prog)
    py_ast.parse(out)  # must always be valid Python
    return out


HEADER = "# Generated by AGK-Real v2 - do not edit\n"


# -- functions --------------------------------------------------------------------

def test_simple_function():
    assert gen("define function f:\n    return 1\n") == (
        HEADER + "def f():\n    return 1\n")


def test_function_params_and_return():
    out = gen(
        "define function add that takes a as Integer, b as Integer "
        "and returns Integer:\n"
        "    return a + b\n")
    assert out == (
        HEADER + "def add(a, b):\n    return a + b\n")


def test_create_emits_nothing_until_set():
    out = gen(
        "define function f:\n"
        "    create x as Integer\n"
        "    set x to 1\n"
        "    return x\n")
    assert out == (
        HEADER + "def f():\n    x = 1\n    return x\n")


def test_main_gets_entrypoint():
    out = gen("define function main:\n    print(\"hi\")\n")
    assert out == (
        HEADER + "def main():\n    print(\"hi\")\n"
        "\nif __name__ == \"__main__\":\n    main()\n")


def test_no_entrypoint_without_main():
    out = gen("define function f:\n    return 1\n")
    assert "__main__" not in out


def test_bare_return():
    out = gen("define function f:\n    return\n")
    assert out == HEADER + "def f():\n    return\n"


def test_multiple_top_level_separated():
    out = gen("import math\ndefine function f:\n    return 1\n")
    assert out == (
        HEADER + "import math\n\ndef f():\n    return 1\n")


# -- constants / imports ---------------------------------------------------------------

def test_constants():
    out = gen("define constant MAX as Integer = 100\n"
              'define constant NAME as String = "agk"\n')
    assert out == HEADER + 'MAX = 100\n\nNAME = "agk"\n'


def test_import():
    assert gen("import math\n") == HEADER + "import math\n"
    assert gen("import os.path\n") == HEADER + "import os.path\n"


# -- control flow -----------------------------------------------------------------------------

def test_if_elif_else():
    out = gen(
        "define function f that takes x as Integer:\n"
        "    if x > 5:\n"
        "        return 1\n"
        "    elif x > 2:\n"
        "        return 2\n"
        "    else:\n"
        "        return 3\n")
    assert out == (
        HEADER +
        "def f(x):\n"
        "    if x > 5:\n"
        "        return 1\n"
        "    elif x > 2:\n"
        "        return 2\n"
        "    else:\n"
        "        return 3\n")


def test_while():
    out = gen(
        "define function f:\n"
        "    create i as Integer\n"
        "    set i to 3\n"
        "    while i > 0:\n"
        "        set i to i - 1\n"
        "    return i\n")
    assert out == (
        HEADER +
        "def f():\n"
        "    i = 3\n"
        "    while i > 0:\n"
        "        i = i - 1\n"
        "    return i\n")


def test_for_each():
    out = gen(
        "define function f that takes items as List:\n"
        "    for each item in items:\n"
        "        print(item)\n")
    assert out == (
        HEADER +
        "def f(items):\n"
        "    for item in items:\n"
        "        print(item)\n")


