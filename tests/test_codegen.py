# -- classes -----------------------------------------------------------------------------

def test_class_fields_constructor_method():
    out = gen(
        "define class Person:\n"
        "    variable name as String\n"
        "    define constructor that takes n as String:\n"
        "        set name to n\n"
        "    define function greet that returns String:\n"
        "        return name\n")
    assert out == (
        HEADER +
        "class Person:\n"
        "    def __init__(self, n):\n"
        "        self.name = n\n"
        "    def greet(self):\n"
        "        return self.name\n")


def test_class_extends():
    out = gen(
        "define class Animal:\n"
        "    variable legs as Integer\n"
        "define class Dog extends Animal:\n"
        "    variable name as String\n")
    assert out == (
        HEADER +
        "class Animal:\n"
        "    def __init__(self):\n"
        "        self.legs = None\n"
        "\n"
        "class Dog(Animal):\n"
        "    def __init__(self):\n"
        "        self.name = None\n")


def test_class_method_call_and_instantiation():
    out = gen(
        "define class Counter:\n"
        "    variable n as Integer\n"
        "    define constructor:\n"
        "        set n to 0\n"
        "    define function bump:\n"
        "        set n to n + 1\n"
        "define function main:\n"
        "    create c as Object\n"
        "    set c to Counter()\n"
        "    c.bump()\n")
    assert "class Counter:\n" in out
    assert "    def __init__(self):\n        self.n = 0\n" in out
    assert "    def bump(self):\n        self.n = self.n + 1\n" in out
    assert "    c = Counter()\n    c.bump()\n" in out
    assert out.rstrip().endswith("main()")


def test_explicit_self_preserved():
    out = gen(
        "define class C:\n"
        "    variable x as Integer\n"
        "    define function get that returns Integer:\n"
        "        return self.x\n")
    assert "        return self.x\n" in out
